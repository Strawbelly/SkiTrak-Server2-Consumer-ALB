#!/usr/bin/env python3
"""
Pulls ALB CloudWatch metrics for a test window using the AWS CLI.

Only metrics that are visible at the load balancer and nowhere else are fetched:
  - HTTPCode_ELB_5XX_Count     errors generated by the ALB itself (no healthy target, overload)
  - HTTPCode_Target_5XX_Count  errors returned by the ingest servers
  - HealthyHostCount           targets in service during the run
  - TargetResponseTime         server-side latency, excluding the client-to-ALB network
Host CPU, memory, and network come from host_monitor.py, and request counts per server
from the Tomcat access logs (CloudWatch does not break ALB requests down by instance).

Writes <out>/cloudwatch.csv (label,timestamp,value) and prints totals.

Usage:
  cloudwatch_fetch.py --start EPOCH --end EPOCH --alb ski-ingest-alb --tg ski-ingest-tg --out results/run1
"""
import argparse
import csv
import json
import os
import subprocess
import tempfile
from datetime import datetime, timezone


def aws(region, *args):
    out = subprocess.run(["aws", "--region", region, "--output", "json", *args],
                         check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def arn_suffix(arn):
    # CloudWatch dimension values are the resource part of the ARN:
    #   ...:loadbalancer/app/name/id -> app/name/id
    #   ...:targetgroup/name/id      -> targetgroup/name/id
    resource = arn.rsplit(":", 1)[1]
    return resource[len("loadbalancer/"):] if resource.startswith("loadbalancer/") else resource


def query(qid, metric, dims, stat, label, period):
    return {
        "Id": qid,
        "Label": label,
        "MetricStat": {
            "Metric": {"Namespace": "AWS/ApplicationELB", "MetricName": metric,
                       "Dimensions": [{"Name": k, "Value": v} for k, v in dims.items()]},
            "Period": period,
            "Stat": stat,
        },
    }


def iso(epoch):
    return datetime.fromtimestamp(epoch, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--start", type=float, required=True, help="epoch seconds")
    p.add_argument("--end", type=float, required=True, help="epoch seconds")
    p.add_argument("--region", default="us-west-2")
    p.add_argument("--alb", required=True, help="load balancer name")
    p.add_argument("--tg", required=True, help="target group name")
    p.add_argument("--period", type=int, default=60)
    p.add_argument("--out", required=True)
    args = p.parse_args()

    # Pad the window so the partial minutes at both ends are included.
    start, end = int(args.start) - 60, int(args.end) + 120

    lb = aws(args.region, "elbv2", "describe-load-balancers", "--names", args.alb)
    tg = aws(args.region, "elbv2", "describe-target-groups", "--names", args.tg)
    alb = {"LoadBalancer": arn_suffix(lb["LoadBalancers"][0]["LoadBalancerArn"])}
    tg_dims = dict(alb, TargetGroup=arn_suffix(tg["TargetGroups"][0]["TargetGroupArn"]))
    queries = [
        query("elb5xx", "HTTPCode_ELB_5XX_Count", alb, "Sum", "alb.ELB5XX", args.period),
        query("target5xx", "HTTPCode_Target_5XX_Count", alb, "Sum", "alb.Target5XX", args.period),
        query("rt_avg", "TargetResponseTime", alb, "Average", "alb.TargetResponseTime.avg_s", args.period),
        query("healthy", "HealthyHostCount", tg_dims, "Minimum", "tg.HealthyHostCount.min", args.period),
    ]

    results = {}
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as tf:
        json.dump(queries, tf)
    try:
        token = None
        while True:
            extra = ["--next-token", token] if token else []
            resp = aws(args.region, "cloudwatch", "get-metric-data",
                       "--metric-data-queries", "file://" + tf.name,
                       "--start-time", iso(start), "--end-time", iso(end), *extra)
            for r in resp["MetricDataResults"]:
                results.setdefault(r["Label"], []).extend(zip(r["Timestamps"], r["Values"]))
            token = resp.get("NextToken")
            if not token:
                break
    finally:
        os.unlink(tf.name)

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, "cloudwatch.csv")
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["label", "timestamp", "value"])
        for label in sorted(results):
            for ts, v in sorted(results[label]):
                w.writerow([label, ts, v])

    print(f"CloudWatch metrics written: {path}")
    for label in sorted(results):
        vals = [v for _, v in results[label]]
        if not vals:
            print(f"  {label:32s} (no data)")
            continue
        print(f"  {label:32s} sum={sum(vals):12.2f} min={min(vals):10.3f} max={max(vals):10.3f}")


if __name__ == "__main__":
    main()
